export function mergeTemplates(overrides: TaskTemplateRow[] | undefined | null): TaskTemplateRow[] {
  if (!overrides || overrides.length === 0) return DEFAULT_TASK_TEMPLATES;
  const byKey = new Map(overrides.map((t) => [t.key, t]));
  const merged = DEFAULT_TASK_TEMPLATES.map((def) => {
    const o = byKey.get(def.key);
    return o ? { ...def, ...o } : def;
  });
  const extra = overrides.filter((t) => !DEFAULT_TASK_TEMPLATES.some((d) => d.key === t.key));
  return [...merged, ...extra].sort((a, b) => a.sortIndex - b.sortIndex);
}
