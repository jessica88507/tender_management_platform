// Admin-editable default scheduling rules. Every task `generateTasks()` (see scheduler.ts) can
// produce has a corresponding row here (matched by `key`). "fixed" and "ratio" rows are fully
// data-driven (anchor/offset or deadline-ratio are read straight from the row); "special" rows
// have hardcoded date logic in scheduler.ts (multi-meeting branching, cross-task dependencies,
// the deadline-time-of-day conditional) but still take their category/label/owner/enabled from
// here so an admin can rename, reassign, or turn off any default task without a code change.

export type TaskTemplateAnchor = "start" | "workStart" | "deadline";
export type TaskTemplateKind = "fixed" | "ratio" | "special";

export interface TaskTemplateRow {
  key: string;
  sortIndex: number;
  category: string;
  label: string;
  owner: string;
  enabled: boolean;
  kind: TaskTemplateKind;
  // Anchor is either one of the 3 fixed case dates (anchor) or another template's computed date
  // (anchorTaskKey, takes precedence when set) — lets a "fixed" row admit it's really derived
  // from another task (e.g. 服務建議書用印 follows 服務建議書送印, not 投標截止 directly) so
  // editing the parent's rule correctly cascades instead of both being independently pinned to
  // the same case date. See scheduler.ts's resolveFixedDate.
  anchor?: TaskTemplateAnchor;
  anchorTaskKey?: string | null;
  offsetDays?: number;
  ratioPct?: number;
  snap?: boolean;
  milestone?: string | null;
  note?: string;
}

